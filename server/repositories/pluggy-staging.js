'use strict';

async function ensureConnectionsTable(conn, { includeStatusIndex = true } = {}) {
  const sql = `
BEGIN
  EXECUTE IMMEDIATE q'[
    CREATE TABLE conexoes_bancarias (
      id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_user_id VARCHAR2(128) NOT NULL,
      pluggy_item_id VARCHAR2(128) NOT NULL,
      provider_name VARCHAR2(256),
      status VARCHAR2(64),
      raw_json CLOB CHECK (raw_json IS JSON),
      source_system VARCHAR2(32) DEFAULT 'PLUGGY' NOT NULL,
      created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
    )
  ]';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;`;
  const uq = `
BEGIN
  EXECUTE IMMEDIATE q'[CREATE UNIQUE INDEX uq_conexoes_bancarias_item ON conexoes_bancarias (tenant_user_id, pluggy_item_id)]';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;`;
  const ix = `
BEGIN
  EXECUTE IMMEDIATE q'[CREATE INDEX ix_conexoes_bancarias_status ON conexoes_bancarias (tenant_user_id, status, updated_at)]';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;`;
  await conn.execute(sql);
  await conn.execute(uq);
  if (includeStatusIndex) await conn.execute(ix);
}

async function ensureTransactionsTable(conn) {
  const sql = `
BEGIN
  EXECUTE IMMEDIATE q'[
    CREATE TABLE transacoes_pluggy (
      id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_user_id VARCHAR2(128) NOT NULL,
      pluggy_item_id VARCHAR2(64),
      pluggy_account_id VARCHAR2(64),
      external_transaction_id VARCHAR2(128) NOT NULL,
      record_type VARCHAR2(24) DEFAULT 'TRANSACTION' NOT NULL,
      transaction_date TIMESTAMP WITH TIME ZONE,
      description VARCHAR2(512),
      amount NUMBER(18,2),
      currency_code VARCHAR2(8),
      account_name VARCHAR2(256),
      account_type VARCHAR2(64),
      balance_amount NUMBER(18,2),
      raw_json CLOB CHECK (raw_json IS JSON),
      source_system VARCHAR2(32) DEFAULT 'PLUGGY' NOT NULL,
      created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
    )
  ]';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;`;
  const uq = `
BEGIN
  EXECUTE IMMEDIATE q'[CREATE UNIQUE INDEX uq_transacoes_pluggy_ext ON transacoes_pluggy (tenant_user_id, external_transaction_id)]';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;`;
  const ix = `
BEGIN
  EXECUTE IMMEDIATE q'[CREATE INDEX ix_transacoes_pluggy_dt ON transacoes_pluggy (tenant_user_id, transaction_date)]';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;`;
  await conn.execute(sql);
  await conn.execute(uq);
  await conn.execute(ix);
}

const CONNECTION_SQL = `
MERGE INTO conexoes_bancarias c
USING (
  SELECT :tenant_user_id AS tenant_user_id, :pluggy_item_id AS pluggy_item_id FROM dual
) src
ON (
  c.tenant_user_id = src.tenant_user_id
  AND c.pluggy_item_id = src.pluggy_item_id
)
WHEN MATCHED THEN UPDATE SET
  c.provider_name = :provider_name,
  c.status = :status,
  c.raw_json = :raw_json,
  c.updated_at = SYSTIMESTAMP
WHEN NOT MATCHED THEN INSERT (
  tenant_user_id,
  pluggy_item_id,
  provider_name,
  status,
  raw_json,
  source_system,
  created_at,
  updated_at
) VALUES (
  :tenant_user_id,
  :pluggy_item_id,
  :provider_name,
  :status,
  :raw_json,
  'PLUGGY',
  SYSTIMESTAMP,
  SYSTIMESTAMP
)`;

const TRANSACTION_SQL = `
MERGE INTO transacoes_pluggy t
USING (
  SELECT
    :tenant_user_id AS tenant_user_id,
    :external_transaction_id AS external_transaction_id
  FROM dual
) src
ON (
  t.tenant_user_id = src.tenant_user_id
  AND t.external_transaction_id = src.external_transaction_id
)
WHEN MATCHED THEN UPDATE SET
  t.pluggy_item_id = :pluggy_item_id,
  t.pluggy_account_id = :pluggy_account_id,
  t.record_type = :record_type,
  t.transaction_date = :transaction_date,
  t.description = :description,
  t.amount = :amount,
  t.currency_code = :currency_code,
  t.account_name = :account_name,
  t.account_type = :account_type,
  t.balance_amount = :balance_amount,
  t.raw_json = :raw_json,
  t.updated_at = SYSTIMESTAMP
WHEN NOT MATCHED THEN INSERT (
  tenant_user_id,
  pluggy_item_id,
  pluggy_account_id,
  external_transaction_id,
  record_type,
  transaction_date,
  description,
  amount,
  currency_code,
  account_name,
  account_type,
  balance_amount,
  raw_json,
  source_system,
  created_at,
  updated_at
) VALUES (
  :tenant_user_id,
  :pluggy_item_id,
  :pluggy_account_id,
  :external_transaction_id,
  :record_type,
  :transaction_date,
  :description,
  :amount,
  :currency_code,
  :account_name,
  :account_type,
  :balance_amount,
  :raw_json,
  'PLUGGY',
  SYSTIMESTAMP,
  SYSTIMESTAMP
)`;

// Webhook updates must not erase balance fields maintained by the sync worker.
const WEBHOOK_TRANSACTION_SQL = TRANSACTION_SQL
  .replace('  t.balance_amount = :balance_amount,\n', '')
  .replace('  balance_amount,\n', '')
  .replace('  :balance_amount,\n', '');

function upsertConnection(conn, binds, options) {
  return options === undefined ? conn.execute(CONNECTION_SQL, binds) : conn.execute(CONNECTION_SQL, binds, options);
}

function upsertTransaction(conn, binds, { includeBalance = true, executeOptions } = {}) {
  const sql = includeBalance ? TRANSACTION_SQL : WEBHOOK_TRANSACTION_SQL;
  const options = executeOptions === undefined && includeBalance ? { autoCommit: false } : executeOptions;
  return options === undefined ? conn.execute(sql, binds) : conn.execute(sql, binds, options);
}

module.exports = { ensureConnectionsTable, ensureTransactionsTable, upsertConnection, upsertTransaction };
